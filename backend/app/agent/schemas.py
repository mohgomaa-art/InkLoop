"""
InkLoop S9 Agent Runtime Contracts and Schemas.
Defines typed models for tool registrations, tool invocations, plans, approvals,
attachments, sessions, and durable execution traces.
"""
from datetime import datetime, timezone
from enum import Enum
from typing import Dict, Any, List, Optional, Union
from pydantic import BaseModel, Field, ConfigDict

from app.contracts.engine import EngineId, EngineStatus
from app.contracts.errors import ErrorCode

class CapabilityStatus(str, Enum):
    """Runtime availability status for a capability or tool."""
    AVAILABLE = "AVAILABLE"
    EXPERIMENTAL = "EXPERIMENTAL"
    BLOCKED = "BLOCKED"
    NOT_IMPLEMENTED = "NOT_IMPLEMENTED"

class SideEffectType(str, Enum):
    """Classification of tool side-effects for policy and approval enforcement."""
    READ_ONLY = "READ_ONLY"
    CREATES_ASSET = "CREATES_ASSET"
    MUTATES_PROJECT_CANON = "MUTATES_PROJECT_CANON"
    SPENDS_PROVIDER_BUDGET = "SPENDS_PROVIDER_BUDGET"
    DESTRUCTIVE_IRREVERSIBLE = "DESTRUCTIVE_IRREVERSIBLE"

class CostSemantics(str, Enum):
    """Cost estimation accuracy and metering classification."""
    FREE = "FREE"
    ESTIMATED = "ESTIMATED"
    METERED_KNOWN = "METERED_KNOWN"
    UNKNOWN = "UNKNOWN"

class ToolDefinition(BaseModel):
    """Canonical registry entry for an Agent-callable tool."""
    tool_id: str = Field(..., description="Unique stable identifier (e.g. 'workspace.list_projects')")
    version: str = Field(default="1.0.0", description="Semantic version of tool contract")
    name: str = Field(..., description="Human-readable display name")
    domain: str = Field(..., description="Domain group (e.g. 'workspace', 'canon', 'generation', 'inspection')")
    owning_service: str = Field(default="shared", description="Underlying engine or service owning the tool")
    purpose: str = Field(..., description="Concise summary of tool action and side effects")
    status: CapabilityStatus = Field(default=CapabilityStatus.AVAILABLE)
    status_reason: Optional[str] = Field(default=None, description="Explanation if BLOCKED or NOT_IMPLEMENTED")
    parameters_schema: Dict[str, Any] = Field(default_factory=dict, description="JSON Schema for tool arguments")
    output_schema: Dict[str, Any] = Field(default_factory=dict, description="JSON Schema for returned tool output")
    side_effect: SideEffectType = Field(default=SideEffectType.READ_ONLY)
    requires_approval: bool = Field(default=False, description="Whether tool execution requires human sign-off")
    cost_semantics: CostSemantics = Field(default=CostSemantics.FREE)
    estimated_cost_usd: Optional[float] = Field(default=0.0)
    is_idempotent: bool = Field(default=True, description="Whether repeating the operation with same inputs is safe")
    timeout_seconds: float = Field(default=30.0)
    is_callable: bool = Field(default=True)

class ToolCall(BaseModel):
    """Invocation request for a registered tool."""
    call_id: str
    tool_id: str
    arguments: Dict[str, Any] = Field(default_factory=dict)

class ToolResult(BaseModel):
    """Outcome and artifacts produced by a tool execution."""
    call_id: str
    tool_id: str
    status: str = "success"  # "success", "failed", "gated", "blocked"
    output: Optional[Dict[str, Any]] = None
    error: Optional[str] = None
    error_code: Optional[str] = None
    duration_seconds: float = 0.0
    artifacts: List[Dict[str, Any]] = Field(default_factory=list)
    cost_usd: Optional[float] = None
    requires_approval: bool = False
    approval_id: Optional[str] = None

class AgentStep(BaseModel):
    """A discrete step in an Agent execution plan."""
    step_id: str
    title: str
    engine_id: str
    tool_name: str
    dependencies: List[str] = Field(default_factory=list)
    required_inputs: Dict[str, Any] = Field(default_factory=dict)
    expected_outputs: List[str] = Field(default_factory=list)
    requires_approval: bool = False
    estimated_cost_usd: Optional[float] = 0.0
    status: str = "pending"

class AgentPlanStatus(str, Enum):
    DRAFT = "DRAFT"
    PLANNED = "PLANNED"
    VALIDATING = "VALIDATING"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    READY = "READY"
    RUNNING = "RUNNING"
    VERIFYING = "VERIFYING"
    COMPLETED = "COMPLETED"
    REJECTED = "REJECTED"
    BLOCKED = "BLOCKED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"

class AgentPlan(BaseModel):
    """Structured DAG plan generated by the Coordinator."""
    plan_id: str
    plan_version: int = 1
    plan_hash: str = ""
    project_id: str
    goal: str
    acceptance_criteria: List[str] = Field(default_factory=list)
    status: AgentPlanStatus = AgentPlanStatus.DRAFT
    steps: List[AgentStep] = Field(default_factory=list)
    canon_version: int = 1
    canon_hash: Optional[str] = ""
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    budget_limit_usd: Optional[float] = None
    project_available_budget_usd: float = Field(default=0.0, description="Authoritative project-level available balance")
    requested_run_budget_cap_usd: Optional[float] = Field(default=None, description="Explicit user per-run ceiling")
    effective_run_budget_cap_usd: float = Field(default=0.0, description="Tighter applicable bound governing dispatch")
    is_cost_unknown: bool = Field(default=False, description="True if plan steps lack verifiable cost estimates")
    dispatched: bool = Field(default=False, description="True if the plan was dispatched for execution")
    dispatch_blocked_reason: Optional[str] = Field(default=None, description="Reason if dispatch was blocked or rejected")

    @property
    def total_estimated_cost_usd(self) -> float:
        return sum(s.estimated_cost_usd or 0.0 for s in self.steps)

class ApprovalStatus(str, Enum):
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    INVALIDATED = "INVALIDATED"

class ApprovalRequest(BaseModel):
    """Cryptographic human-in-the-loop sign-off record for gated operations."""
    approval_id: str
    plan_id: Optional[str] = None
    step_id: Optional[str] = None
    operation: str
    scope: str
    affected_resources: List[str] = Field(default_factory=list)
    reversibility: str = "IRREVERSIBLE"  # "REVERSIBLE" | "IRREVERSIBLE"
    consequence: str
    cost_exposure_usd: Optional[float] = 0.0
    status: ApprovalStatus = ApprovalStatus.PENDING
    canon_hash_at_request: Optional[str] = ""
    arguments_hash: str = ""
    proposed_changes: Optional[Dict[str, Any]] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    decided_at: Optional[str] = None
    decision: Optional[str] = None
    decision_rationale: Optional[str] = None

class AgentAttachment(BaseModel):
    """Metadata for an image or file attached to the conversation."""
    attachment_id: str
    filename: str
    mime_type: str
    byte_size: int
    content_sha256: str
    width: Optional[int] = None
    height: Optional[int] = None
    asset_id: Optional[str] = None
    is_canonical_anchor: bool = False
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

class ModelUsage(BaseModel):
    """Provider-reported usage only; missing provider meters stay unknown."""
    status: str = Field(..., pattern="^(reported|partial|unavailable)$")
    model_calls: int = Field(default=0, ge=0)
    input_tokens: Optional[int] = Field(default=None, ge=0)
    output_tokens: Optional[int] = Field(default=None, ge=0)
    total_tokens: Optional[int] = Field(default=None, ge=0)

class PendingStoryAction(BaseModel):
    """Durable state for a detected story narrative awaiting creator review and production dispatch."""
    schema_version: str = "1.0.0"
    action_type: str = "adapt_story_to_comic"
    source_message_id: str
    source_story_hash: str
    source_title: str
    status: str = "offer_made"  # planning | offer_made | plan_ready | running | needs_attention | completed | skipped
    panel_count: int = 6
    page_count: Optional[int] = Field(default=None, ge=1, le=50)
    total_panel_count: Optional[int] = Field(default=None, ge=0)
    page_panel_counts: Dict[str, int] = Field(default_factory=dict)
    estimated_cost_usd: Optional[float] = Field(default=None, ge=0)
    assumptions: List[str] = Field(default_factory=list)
    plan: Optional[Dict[str, Any]] = None
    plan_call_id: Optional[str] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

class AgentMessage(BaseModel):
    """A single turn in the conversational transcript."""
    message_id: str
    role: str  # "user" | "assistant" | "system" | "tool"
    text: str
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    attachments: List[AgentAttachment] = Field(default_factory=list)
    request_context: Dict[str, Any] = Field(default_factory=dict)
    tool_calls: List[ToolCall] = Field(default_factory=list)
    tool_results: List[ToolResult] = Field(default_factory=list)
    activity_state: Optional[str] = "idle"
    activity_label: Optional[str] = None
    plan: Optional[AgentPlan] = None
    pending_approval: Optional[ApprovalRequest] = None
    project_available_budget_usd: Optional[float] = None
    requested_run_budget_cap_usd: Optional[float] = None
    model_usage: Optional[ModelUsage] = None
    production_job: Optional[Dict[str, Any]] = None
    pending_story_action: Optional[PendingStoryAction] = None

class AgentSession(BaseModel):
    """A durable conversational Agent session."""
    session_id: str
    project_id: str
    title: str = "New Conversation"
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    messages: List[AgentMessage] = Field(default_factory=list)
    active_plan_id: Optional[str] = None
    active_run_id: Optional[str] = None
    metadata: Dict[str, Any] = Field(default_factory=dict)
