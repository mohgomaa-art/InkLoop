"""
InkLoop Shared Specialist Engine Execution Contracts.
Defines typed request/response protocols, run tracking, usage metrics, and provenance.
"""
from datetime import datetime, timezone
from enum import Enum
from typing import TypeVar, Generic, Optional, List, Dict, Any
from pydantic import BaseModel, Field
from app.contracts.errors import ValidationErrorDetail, EngineFailure

TParams = TypeVar("TParams")
TOutput = TypeVar("TOutput")

class EngineId(str, Enum):
    """Authoritative identifiers for the seven specialist production engines and core services."""
    E1_IMAGE_GENERATION = "e1_image_generation"
    E2_CANVAS_GENERATION = "e2_canvas_generation"
    E3_IMAGE_CANVAS_INTEGRATION = "e3_image_canvas_integration"
    E4_TEXT_GENERATION = "e4_text_generation"
    E5_TYPOGRAPHY_FONT = "e5_typography_font"
    E6_SPEECH_BUBBLE = "e6_speech_bubble"
    E7_EFFECTS_MOTION = "e7_effects_motion"
    S6_COMPOSITOR = "s6_compositor"
    S7_QUALITY_VERIFICATION = "s7_quality_verification"
    S8_EXPORT_DELIVERY = "s8_export_delivery"

class EngineStatus(str, Enum):
    """Standardized lifecycle status for an engine execution attempt."""
    PENDING = "pending"
    RUNNING = "running"
    SUCCESS = "success"
    FAILED = "failed"
    CANCELLED = "cancelled"
    NOT_IMPLEMENTED_YET = "not_implemented_yet"
    EXPERIMENTAL = "experimental"
    NEEDS_REVIEW = "needs_review"

class UsageMetrics(BaseModel):
    """Resource and financial accounting metrics for an execution."""
    input_tokens: int = Field(default=0, description="Tokens supplied to provider input")
    output_tokens: int = Field(default=0, description="Tokens generated by provider")
    total_tokens: int = Field(default=0, description="Combined token volume")
    image_ops: int = Field(default=0, description="Number of image-generation or edit operations")
    compute_seconds: float = Field(default=0.0, description="Wall-clock execution latency in seconds")
    estimated_cost_usd: float = Field(default=0.0, description="Locally computed cost estimate in USD")
    provider_reported_cost_usd: Optional[float] = Field(default=None, description="Actual billing cost if returned by provider API")

class ProvenanceRecord(BaseModel):
    """Immutable audit trail recording the origin and dependencies of an execution."""
    engine_id: EngineId
    engine_version: str = Field(default="1.0.0", description="Semver of the executing engine implementation")
    config_hash: str = Field(..., description="SHA-256 digest of parameters, canon state, and configuration")
    input_artifact_ids: List[str] = Field(default_factory=list, description="IDs of artifacts consumed as input")
    story_bible_version: Optional[str] = Field(default=None, description="Story Bible snapshot version at execution time")
    taxonomy_rule_ids: List[str] = Field(default_factory=list, description="IDs of 60-group taxonomy rules applied")
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat(), description="ISO 8601 UTC timestamp")

class EngineRunRequest(BaseModel, Generic[TParams]):
    """Standardized invocation envelope for all InkLoop specialist engines."""
    run_id: str = Field(..., description="Unique run identifier (e.g. 'run_01h8x...')")
    attempt_id: str = Field(default="att_01", description="Attempt counter/identifier within run")
    engine_id: EngineId = Field(..., description="Target specialist engine")
    engine_version: str = Field(default="1.0.0", description="Expected engine semver")
    project_id: str = Field(..., description="Parent project identifier")
    scope_id: Optional[str] = Field(default=None, description="Target scene_id, panel_id, or page_id if applicable")
    input_artifact_ids: List[str] = Field(default_factory=list, description="Prerequisite input artifact references")
    parameters: TParams = Field(..., description="Engine-specific parameter payload")
    config_hash: str = Field(..., description="Deterministic hash of parameters and active state")
    budget_limit_usd: Optional[float] = Field(default=None, description="Optional spend ceiling for this invocation")
    dry_run: bool = Field(default=False, description="If True, validates contracts and returns mock/plan without provider calls")

class EngineRunResponse(BaseModel, Generic[TOutput]):
    """Standardized output envelope returned by all InkLoop specialist engines."""
    run_id: str
    attempt_id: str
    engine_id: EngineId
    engine_version: str
    status: EngineStatus
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    completed_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    latency_seconds: float = Field(default=0.0)
    output_artifact_ids: List[str] = Field(default_factory=list, description="IDs of newly created artifacts")
    output: Optional[TOutput] = Field(default=None, description="Engine-specific structured result")
    usage: UsageMetrics = Field(default_factory=UsageMetrics)
    provenance: ProvenanceRecord
    validation_errors: List[ValidationErrorDetail] = Field(default_factory=list)
    error: Optional[EngineFailure] = Field(default=None, description="Failure details if status is FAILED")
    retryable: bool = Field(default=False, description="Whether retry is permitted under budget bounds")
